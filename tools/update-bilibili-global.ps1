param(
  [string]$BasePluginPath = "Plugins/bilibili.lpx",
  [string]$TargetPath = "Plugins/bilibili-global.lpx",
  [string]$ReleaseApiUrl = "https://api.github.com/repos/Biliverse/Global/releases/latest",
  [string]$CoreResponseUrl = "https://rucu6.pages.dev/Scripts/bilibili/response.js"
)

$ErrorActionPreference = "Stop"
$client = [Net.WebClient]::new()
$client.Encoding = [Text.Encoding]::UTF8
$client.Headers.Set("User-Agent", "Loon/3.5.1 zwjtano-loon-sync")

function Read-RemoteText {
  param([string]$Url)
  $textClient = [Net.WebClient]::new()
  $textClient.Encoding = [Text.Encoding]::UTF8
  $textClient.Headers.Set("User-Agent", "Loon/3.5.1")
  $textClient.Headers.Set("Accept", "application/vnd.github+json,text/plain,*/*")
  if (([Uri]$Url).Host -eq 'api.github.com' -and $env:GH_TOKEN) {
    $textClient.Headers.Set("Authorization", "Bearer $env:GH_TOKEN")
  }
  try { return $textClient.DownloadString($Url) -replace "`r`n", "`n" }
  finally { $textClient.Dispose() }
}

function Read-ReleaseAsset {
  param([string]$Name)
  $asset = @($release.assets | Where-Object name -EQ $Name)
  if ($asset.Count -ne 1 -or $asset[0].digest -notmatch '^sha256:([0-9a-f]{64})$') {
    throw "Missing or unverifiable Global release asset: $Name"
  }
  $expected = $Matches[1]
  $bytes = $client.DownloadData($asset[0].browser_download_url)
  $hash = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($bytes)).ToLowerInvariant()
  if ($hash -cne $expected) { throw "Global release asset digest mismatch: $Name" }
  $assetDigests[$Name] = $hash
  return [Text.Encoding]::UTF8.GetString($bytes) -replace "`r`n", "`n"
}

$base = Get-Content -Raw -LiteralPath $BasePluginPath
$base = $base -replace "`r`n", "`n"
if (-not $base.StartsWith('#!name=') -or -not $base.Contains('Scripts/bilibili/popular.js')) {
  throw "The base plugin must be generated by tools/update-bilibili.ps1 first."
}
$release = Read-RemoteText $ReleaseApiUrl | ConvertFrom-Json
$assetDigests = [ordered]@{}
$globalPlugin = Read-ReleaseAsset "BiliBili.Global.plugin"
$globalRequest = Read-ReleaseAsset "request.bundle.js"
$globalResponse = Read-ReleaseAsset "response.bundle.js"
$adResponse = Read-RemoteText $CoreResponseUrl
if (-not $globalPlugin.Contains('[Script]') -or -not $adResponse.Contains('viewunite.v1.View/View')) {
  throw "Invalid upstream plugin or script. Global plugin length: $($globalPlugin.Length); core preview: $($adResponse.Substring(0, [Math]::Min(100, $adResponse.Length)))"
}
foreach ($bundle in @($globalRequest, $globalResponse)) {
  if (-not $bundle.Contains('globalThis.$argument') -or $bundle.TrimStart().StartsWith('<')) {
    throw "Global runtime changed; review stage-local argument isolation before publishing."
  }
  foreach ($global in @('globalThis.$request', 'globalThis.$response', 'globalThis.$done')) {
    if ($bundle.Contains($global)) { throw "Unsupported Global runtime dependency: $global" }
  }
}

$template = Get-Content -Raw -LiteralPath "tools/templates/bilibili-global.js"
$engine = $template.Replace('/*__GLOBAL_REQUEST__*/', $globalRequest.Replace('globalThis.$argument', '$argument'))
$engine = $engine.Replace('/*__GLOBAL_RESPONSE__*/', $globalResponse.Replace('globalThis.$argument', '$argument'))
$engine = $engine.Replace('/*__AD_RESPONSE__*/', $adResponse)

$rawBase = "https://raw.githubusercontent.com/zwjtano/loon-/master"
$allArguments = '${globalEnabled}, ${globalForceHost}, ${globalLocales}, ${globalProxyCHN}, ${globalProxyHKG}, ${globalProxyMAC}, ${globalProxyTWN}, ${globalStorage}, ${globalLogLevel}, ${displayUpList}, ${purifyComment}, ${sponsorBlock}, ${logLevel}'
$globalArgumentLines = @'
globalEnabled=switch, true, false, tag=开启「Global」, desc=整合版内置 Global；不要同时启用独立 Global 或原净化插件
globalForceHost=select, "1", "0", "2", tag=Global「CDN类型」, desc=1 HTTP；0 IP；2 HTTPS
globalLocales=input, "CHN,HKG,TWN", tag=Global「启用地区」, desc=用英文逗号分隔 CHN,HKG,MAC,TWN
globalProxyCHN=input, "DIRECT", tag=Global「大陆策略」, desc=填写 Loon 中实际存在的节点或策略组名称
globalProxyHKG=input, "香港", tag=Global「香港策略」, desc=填写 Loon 中实际存在的节点或策略组名称
globalProxyMAC=input, "澳门", tag=Global「澳门策略」, desc=填写 Loon 中实际存在的节点或策略组名称
globalProxyTWN=input, "台湾", tag=Global「台湾策略」, desc=填写 Loon 中实际存在的节点或策略组名称
globalStorage=select, "Argument", "PersistentStore", "database", tag=Global「配置来源」, desc=Argument 使用插件参数；PersistentStore 使用已有 BoxJS 设置；database 使用上游默认值
globalLogLevel=select, "WARN", "OFF", "ERROR", "INFO", "DEBUG", "ALL", tag=Global「日志等级」, desc=Global 日志等级独立于净化脚本
'@

$globalRules = [Collections.Generic.List[string]]::new()
$globalRewrites = [Collections.Generic.List[string]]::new()
$globalHosts = @()
$globalParameters = [Collections.Generic.List[string]]::new()
$section = ""
$responseViewFound = $false
foreach ($line in ($globalPlugin -split "`n")) {
  if ($line -match '^\[(.+)\]$') { $section = $Matches[1]; continue }
  if ($section -eq 'Argument' -and $line -match '^([A-Za-z][\w.]*)\s*=') {
    $globalParameters.Add($Matches[1])
  } elseif ($section -eq 'Script' -and $line.Trim() -and -not $line.StartsWith('#')) {
    if ($line -notmatch '^http-(request|response)\s+(\S+)\s+(.+)$') {
      throw "Unsupported Global script rule format: $line"
    }
    $type = $Matches[1]; $pattern = $Matches[2]; $settings = $Matches[3]
    if ($type -eq 'response' -and $pattern.Contains('viewunite')) { $responseViewFound = $true }
    $requiresBody = $settings -match 'requires-body=(1|true)'
    $binary = $settings -match 'binary-body-mode=(1|true)'
    if ($settings -notmatch 'tag=[^,]*BiliBili\.Global\.([^,]+)') {
      throw "Global script tag changed; cannot identify endpoint: $pattern"
    }
    $tag = ('Global + Ads: ' + $Matches[1].Trim()) | ConvertTo-Json -Compress
    $rule = $type + ' if ${url} ~= /' + $pattern + '/i then script("' + $rawBase + '/Scripts/bilibili/global-integration.js", {' + $allArguments + '}) with tag=' + $tag + ', timeout=60'
    if ($requiresBody) { $rule += ', requires_body=true' }
    if ($binary) { $rule += ', binary_body_mode=true' }
    $globalRules.Add($rule)
  } elseif ($section -eq 'Rewrite' -and $line.StartsWith('response if ')) {
    $globalRewrites.Add($line.Replace('response if ', 'response if ${globalEnabled} == true && '))
  } elseif ($section -eq 'MitM' -and $line -match '^hostname\s*=\s*(.+)$') {
    $globalHosts = $Matches[1] -split ',' | ForEach-Object { $_.Trim() }
  }
}
if (-not $responseViewFound -or $globalRules.Count -lt 10 -or $globalHosts.Count -lt 5) {
  throw "Global endpoints or hosts were not fully recognized."
}
$expectedParameters = @('ForceHost', 'Locales', 'Proxies.CHN', 'Proxies.HKG', 'Proxies.MAC', 'Proxies.TWN', 'Storage', 'LogLevel')
if (Compare-Object $expectedParameters $globalParameters) {
  throw "Global parameter schema changed; review the integration mapping before publishing."
}

$output = [Collections.Generic.List[string]]::new()
$removedPaymentRewrite = $false
$splitCoreViewRule = $false
foreach ($line in ($base -split "`n")) {
  if ($line.StartsWith('#!name=')) { $output.Add('#!name=哔哩哔哩 + Global（整合测试版）'); continue }
  if ($line.StartsWith('#!desc=')) { $output.Add('#!desc=Global 地区识别、线路与搜索功能 + 自定义净化。测试时仅启用此插件，并填写实际存在的地区策略组。'); continue }
  if ($line.StartsWith('#!loon_version=')) { $output.Add('#!loon_version=3.5.1(983)'); continue }
  if ($line.StartsWith('#!author=')) { $output.Add($line + ', VirgilClyne[https://github.com/VirgilClyne]'); continue }
  if ($line -eq '[Argument]') {
    $output.Add($line); $output.Add($globalArgumentLines); continue
  }
  if ($line -eq '[Script]') {
    $output.Add($line); foreach ($rule in $globalRules) { $output.Add($rule) }; continue
  }
  if ($line -eq '[Rewrite]') {
    $output.Add($line); foreach ($rule in $globalRewrites) { $output.Add($rule) }; continue
  }
  if ($line -match '^DOMAIN, (api|app)\.biliapi\.(com|net), REJECT$') { continue }
  if ($line.Contains('pgc\/view\/v2\/app\/season') -and $line.Contains('response.json.jq')) {
    $removedPaymentRewrite = $true; continue
  }
  if ($line.Contains('bilibili\.app\.viewunite\.v1\.View\/(?:AIRelateAsync|RelatesFeed|View|ViewProgress)')) {
    $line = $line.Replace('|View|', '|')
    $splitCoreViewRule = $true
  }
  if ($line.StartsWith('hostname=')) {
    $hosts = @($line.Substring(9) -split ',' | ForEach-Object { $_.Trim() }) + $globalHosts
    $output.Add('hostname=' + (($hosts | Select-Object -Unique) -join ', '))
    $output.Add('h2=true'); continue
  }
  if ($line -match '^h2\s*=') { continue }
  $output.Add($line)
}
if (-not $removedPaymentRewrite -or -not $splitCoreViewRule) {
  throw "Core response layout changed; cannot safely merge conflicting handlers."
}

$license = Read-RemoteText "https://raw.githubusercontent.com/Biliverse/Global/main/LICENSE"
if (-not $license.Contains('Apache License') -or -not $license.Contains('Version 2.0')) {
  throw "Unexpected Global license; review before redistribution."
}
$manifest = [ordered]@{
  global_repository = 'https://github.com/Biliverse/Global'
  global_version = $release.tag_name
  global_assets = $assetDigests
  core_response_source = $CoreResponseUrl
  core_response_sha256 = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($adResponse))).ToLowerInvariant()
  transformations = @('Isolate globalThis.$argument to the stage-local binding', 'Run response ad cleanup after Global', 'Clean request-stage synthetic responses before returning')
}
$files = [ordered]@{
  $TargetPath = ($output -join "`n").TrimEnd() + "`n"
  'Scripts/bilibili/global-integration.js' = $engine
  'Scripts/bilibili/global-integration.sources.json' = ($manifest | ConvertTo-Json -Depth 5) + "`n"
  'third_party/biliverse-global/LICENSE' = $license
}
foreach ($entry in $files.GetEnumerator()) {
  $path = Join-Path (Get-Location) $entry.Key
  [IO.Directory]::CreateDirectory((Split-Path -Parent $path)) | Out-Null
  [IO.File]::WriteAllText($path, $entry.Value, [Text.UTF8Encoding]::new($false))
}
Write-Host "Generated $TargetPath with Global $($release.tag_name), $($globalRules.Count) endpoints and chained response cleanup."
